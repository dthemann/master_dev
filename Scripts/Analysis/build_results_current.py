#!/usr/bin/env python
"""Build `results_current/`: one place holding the results the thesis reports.

SYMLINKS, not copies, and deliberately so. Copying would duplicate about 14 GB and
create a second artefact that can drift from the first. Drift between two copies of
the same result is the exact failure this repository has already been through: the
thesis shipped three figures from superseded trees for a week because nothing tied
the printed asset to the tree that wrote it. One source of truth, many pointers.

Every target comes from the canonical-tree table in `repro_harness.py`, so this
directory cannot name a tree the pipeline does not use.

    python Scripts/Analysis/build_results_current.py
    python Scripts/Analysis/build_results_current.py --check   # verify, change nothing
"""
from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from repro_harness import CANONICAL, ROOT  # noqa: E402

OUT = ROOT / "results_current"

# Layout: readable names, grouped the way the thesis is organised.
LINKS = {
    "benchmark/posebusters_screen": "benchmark_pb",
    "benchmark/pose_comparison": "benchmark_report",
    "benchmark/pose_clusters": "benchmark_clusters",
    "benchmark/interaction_fingerprints": "benchmark_pandamap",
    "benchmark/cost_charged": "benchmark_effort_charged",
    "benchmark/cost_elapsed": "benchmark_effort_elapsed",
    "benchmark/exhaustiveness_ladder": "exhaustiveness",
    "orai/control_panel": "orai_control",
    "orai/experimental_panel": "orai_experimental",
    "orai/valid_yield_compare": "orai_yield",
    "orai/tm_share_compare": "orai_tm_share",
    "orai/fingerprints_control": "orai_pandamap_control",
    "orai/fingerprints_experimental": "orai_pandamap_experimental",
    "orai/fingerprints_compare": "orai_pandamap_compare",
    "dataset/figures": "dataset_figures",
}

# Files worth surfacing at the top level rather than buried in a tree.
FILES = {
    "run_manifest.json": "posebusters_results/_reproduction/run_manifest.json",
    "regeneration_check.json": "posebusters_results/_reproduction/regeneration_check.json",
    "thesis_figures": "thesis_latex/media/media",
    "thesis_pdf": "thesis_latex/Thesis_short.pdf",
}

README = """# results_current

The results the thesis reports, in one place.

**These are symlinks, not copies.** The single source of truth stays in the
canonical trees; this directory is a readable index onto them. Copying would
duplicate about 14 GB and create a second artefact free to drift from the first,
which is the failure this repository has already lived through.

Generated by `Scripts/Analysis/build_results_current.py` from the canonical-tree
table in `repro_harness.py`, so it cannot name a tree the pipeline does not use.
Re-run it after any change to that table.

| Link | Points at |
| --- | --- |
"""


def build(check: bool) -> int:
    made = broken = 0
    rows = []
    for name, key in LINKS.items():
        target = CANONICAL.get(key)
        if target is None:
            print(f"  ** {name}: no canonical key {key!r}")
            broken += 1
            continue
        link = OUT / name
        ok = target.exists()
        rows.append((name, target.relative_to(ROOT), ok))
        if not ok:
            print(f"  ** {name} -> {target.relative_to(ROOT)}  TARGET MISSING")
            broken += 1
            continue
        if check:
            state = "ok" if link.is_symlink() and link.resolve() == target.resolve() else "MISSING"
            print(f"  {state:8s} {name} -> {target.relative_to(ROOT)}")
            continue
        link.parent.mkdir(parents=True, exist_ok=True)
        if link.is_symlink() or link.exists():
            link.unlink()
        # relative link, so the tree survives being moved as a whole
        link.symlink_to(os.path.relpath(target, link.parent))
        made += 1

    for name, rel in FILES.items():
        target = ROOT / rel
        ok = target.exists()
        rows.append((name, rel, ok))
        if not ok:
            print(f"  ** {name} -> {rel}  TARGET MISSING")
            broken += 1
            continue
        if check:
            link = OUT / name
            state = "ok" if link.is_symlink() and link.resolve() == target.resolve() else "MISSING"
            print(f"  {state:8s} {name} -> {rel}")
            continue
        link = OUT / name
        link.parent.mkdir(parents=True, exist_ok=True)
        if link.is_symlink() or link.exists():
            link.unlink()
        link.symlink_to(os.path.relpath(target, link.parent))
        made += 1

    if not check:
        body = README + "".join(
            f"| `{n}` | `{t}`{'' if ok else '  **MISSING**'} |\n" for n, t, ok in rows)
        (OUT / "README.md").write_text(body)
        print(f"\n  {made} symlinks, {broken} broken -> {OUT.relative_to(ROOT)}")
    return 1 if broken else 0


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="verify without changing anything")
    args = ap.parse_args(argv)
    return build(args.check)


if __name__ == "__main__":
    sys.exit(main())
